import { Link } from 'react-router-dom';
import { KeyRound, PlugZap, AlertTriangle, Clock, RotateCw, LogIn } from 'lucide-react';
import RichText from '../lesson/RichText';
import { useAuth } from '../../context/AuthContext';
import './AI.css';

/**
 * Status / error banner shared by every AI page.
 * kind: 'not_configured' | 'unavailable' | 'rate_limited' | 'auth_required' | 'error'
 */
const VARIANTS = {
  not_configured: { icon: KeyRound, tone: 'config', title: 'AI is not configured yet' },
  unavailable: { icon: PlugZap, tone: 'error', title: 'API server not reachable' },
  rate_limited: { icon: Clock, tone: 'config', title: 'Slow down a little' },
  auth_required: { icon: LogIn, tone: 'config', title: 'Sign in to use AI features' },
  error: { icon: AlertTriangle, tone: 'error', title: 'Claude couldn’t answer' },
};

export default function AINotice({ kind, message, onRetry, retryLabel = 'Try again' }) {
  const variant = VARIANTS[kind] ?? VARIANTS.error;
  const Icon = variant.icon;
  return (
    <div className={`ai-notice ai-notice--${variant.tone}`} role={kind === 'not_configured' ? 'status' : 'alert'}>
      <Icon size={18} />
      <div className="ai-notice__body">
        <p className="ai-notice__title">{variant.title}</p>
        <p className="ai-notice__text">
          <RichText text={message} />
        </p>
        {kind === 'not_configured' && (
          <p className="ai-notice__text">
            <RichText text="Copy `.env.example` to `.env`, set `ANTHROPIC_API_KEY=…`, then restart with `npm run dev:full`. The key stays on the server and is never sent to the browser." />
          </p>
        )}
      </div>
      {kind === 'auth_required' && (
        <Link className="ai-notice__retry" to={`/auth?next=${encodeURIComponent(window.location.pathname + window.location.search)}`}>
          <LogIn size={14} />
          Sign in
        </Link>
      )}
      {onRetry && kind !== 'auth_required' && (
        <button type="button" className="ai-notice__retry" onClick={onRetry}>
          <RotateCw size={14} />
          {retryLabel}
        </button>
      )}
    </div>
  );
}

/** Small "Powered by Claude" footnote with the model the server is using. */
export function AIFootnote({ model, children }) {
  return (
    <p className="ai-footnote">
      {children ?? 'Generated by Claude. AI answers can contain mistakes, so double-check important details.'}
      {model && <span className="ai-footnote__model"> Model: {model}</span>}
    </p>
  );
}

/**
 * Up-front notice when the server only allows signed-in users to use AI
 * (AI_REQUIRE_AUTH – on by default in production) and nobody is signed in.
 */
export function AIAccessNotice({ status }) {
  const auth = useAuth();
  if (status.state !== 'ready' || !status.requiresAuth || auth.status === 'signed_in' || auth.status === 'loading') return null;
  return <AINotice kind="auth_required" message="The AI features are available to signed-in users. Sign in or create a free account to continue." />;
}
