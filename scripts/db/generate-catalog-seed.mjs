/**
 * npm run db:seed-sql
 *
 * Writes supabase/migrations/20261114120100_catalog_seed.sql from the app's
 * own source data (topics, lesson sections, practice problems), so the
 * database catalog always matches the frontend. The SQL is idempotent
 * (insert … on conflict do update), so re-running it after adding a topic or
 * problem is safe.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import topics from '../../src/data/topics.js';
import LESSON_SECTIONS from '../../src/data/lessonSections.js';
import problems from '../../src/data/practice/problems.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const OUT = path.join(ROOT, 'supabase/migrations/20261114120100_catalog_seed.sql');

const q = (value) => `'${String(value).replace(/'/g, "''")}'`;

const topicRows = topics.map((t, i) => `  (${q(t.id)}, ${q(t.name)}, ${q(t.level)}, ${i + 1}, ${q(t.description ?? '')})`);
const sectionRows = LESSON_SECTIONS.map((s, i) => `  (${q(s.key)}, ${q(s.title)}, ${i + 1})`);
const problemRows = problems.map((p, i) => `  (${q(p.id)}, ${q(p.title)}, ${q(p.difficulty)}, ${q(p.topic)}, ${i + 1})`);

const topicIds = new Set(topics.map((t) => t.id));
const orphans = problems.filter((p) => !topicIds.has(p.topic));
if (orphans.length) {
  console.error(`Problems with unknown topics: ${orphans.map((p) => p.id).join(', ')}`);
  process.exit(1);
}

const sql = `-- =============================================================================
-- AlgoVerse catalog seed – GENERATED by scripts/db/generate-catalog-seed.mjs
-- from src/data/topics.js, src/data/lessonSections.js and
-- src/data/practice/problems.js. Do not edit by hand; run \`npm run db:seed-sql\`.
-- This is the app's real curriculum (no sample/user data). Idempotent.
-- =============================================================================

-- Positions are unique; clear them first so re-ordering never collides.
update public.topics set position = -position where position > 0;
update public.lesson_sections set position = -position where position > 0;
update public.practice_problems set position = -position where position > 0;

insert into public.topics (id, name, level, position, description) values
${topicRows.join(',\n')}
on conflict (id) do update set
  name = excluded.name, level = excluded.level, position = excluded.position, description = excluded.description;

insert into public.lesson_sections (key, title, position) values
${sectionRows.join(',\n')}
on conflict (key) do update set title = excluded.title, position = excluded.position;

insert into public.practice_problems (id, title, difficulty, topic_id, position) values
${problemRows.join(',\n')}
on conflict (id) do update set
  title = excluded.title, difficulty = excluded.difficulty, topic_id = excluded.topic_id, position = excluded.position;
`;

fs.writeFileSync(OUT, sql);
console.log(`Wrote ${path.relative(ROOT, OUT)}: ${topics.length} topics, ${LESSON_SECTIONS.length} sections, ${problems.length} problems.`);
